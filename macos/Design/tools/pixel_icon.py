#!/usr/bin/env python3
"""Generates the pixel-art app icon (concept B: avocado with a USB-C plug).

The icon is drawn on a 32×32 grid and written as SVG with one square per
pixel (crisp edges at any scale):

  appicon/B-pixel.svg          1024×1024, full-bleed (what macOS masks)
  appicon/B-pixel-preview.svg  same, rounded like the final icon (previews only)

Edit the palette or the shape functions below and rerun:
  python3 macos/Design/tools/pixel_icon.py
"""
import math
import os

N = 32          # grid size
SCALE = 32      # 32 × 32 = 1024 px

PALETTE = {
    "bg1": "#f4efd3",  # background, top band
    "bg2": "#e9eecb",
    "bg3": "#dbe8bd",  # background, bottom band
    "out": "#1a2c12",  # outline
    "skin": "#2f5b20",
    "skinhi": "#4f8a33",
    "flesh": "#d4e682",
    "fleshhi": "#eef6bd",
    "fleshlo": "#a9c95a",
    "pit": "#7b4a23",
    "pithi": "#a87240",
    "pitlo": "#4f2d13",
    "metal": "#e6e6e6",
    "metallo": "#a3a3a3",
    "house": "#343434",
    "househi": "#5a5a5a",
    "cable": "#262626",
}


def in_circle(x, y, cx, cy, r):
    return (x + 0.5 - cx) ** 2 + (y + 0.5 - cy) ** 2 <= r * r


def avocado(x, y, shrink=0.0):
    """Pear shape: two circles joined by a tapered neck."""
    top = in_circle(x, y, 16, 10.5, 5.2 - shrink)
    bottom = in_circle(x, y, 16, 20.5, 8.6 - shrink)
    # neck: between the circles, width interpolated
    neck = False
    if 10.5 <= y + 0.5 <= 20.5:
        t = (y + 0.5 - 10.5) / 10.0
        half = (5.2 - shrink) + t * ((8.6 - shrink) - (5.2 - shrink)) * 0.85
        neck = abs(x + 0.5 - 16) <= half
    return top or bottom or neck


def build():
    g = [[None] * N for _ in range(N)]
    # background bands (classic pixel-art banding instead of a gradient)
    for y in range(N):
        band = "bg1" if y < 11 else "bg2" if y < 22 else "bg3"
        for x in range(N):
            g[y][x] = band

    skin = {(x, y) for y in range(N) for x in range(N) if avocado(x, y)}
    flesh = {(x, y) for y in range(N) for x in range(N) if avocado(x, y, shrink=1.9)}
    pit = {(x, y) for y in range(N) for x in range(N) if in_circle(x, y, 16, 20.5, 4.4)}

    def edge(cells, p, dirs=((1, 0), (-1, 0), (0, 1), (0, -1))):
        return any((p[0] + dx, p[1] + dy) not in cells for dx, dy in dirs)

    for p in skin:
        g[p[1]][p[0]] = "skin"
    # skin highlight on the upper-left rim
    for (x, y) in skin:
        if (x - 1, y) not in skin and x < 16 and y < 22 and (x, y) not in flesh:
            g[y][x + 1 if (x + 1, y) in skin and (x + 1, y) not in flesh else x] = "skinhi"
    for p in flesh:
        g[p[1]][p[0]] = "flesh"
    for p in flesh:  # darker ring where the flesh meets the skin
        if edge(flesh, p):
            g[p[1]][p[0]] = "fleshlo"
    for (x, y) in flesh:  # soft highlight, upper left
        if not edge(flesh, (x, y)) and in_circle(x, y, 13.5, 13.5, 2.6):
            g[y][x] = "fleshhi"
    for p in pit:
        g[p[1]][p[0]] = "pit"
    for (x, y) in pit:  # pit shading: dark lower-right rim, light spot upper-left
        if edge(pit, (x, y)) and (x + 0.5 >= 16 or y + 0.5 >= 22):
            g[y][x] = "pitlo"
    for (x, y) in [(13, 18), (14, 18), (13, 19)]:
        g[y][x] = "pithi"
    # 1-px outline around the whole avocado
    for y in range(N):
        for x in range(N):
            if (x, y) not in skin and any((x + dx, y + dy) in skin for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                g[y][x] = "out"

    # USB-C plug: metal tip in the pit, housing below, cable to the bottom edge
    # (all centred on the pit: columns 15-16 are the middle of the 32-px grid)
    for y in (20, 21):
        for x in (15, 16):
            g[y][x] = "metal" if y == 20 else "metallo"
    for y in range(22, 26):
        for x in range(14, 18):
            g[y][x] = "house"
        g[y][14] = "househi"
    for y, xs in ((26, (15, 16)), (27, (15, 16)), (28, (15, 16)), (29, (16, 17)), (30, (16, 17)), (31, (17, 18))):
        for x in xs:
            g[y][x] = "cable"
    return g


def svg(g, rounded):
    size = N * SCALE
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
           f'viewBox="0 0 {N} {N}" shape-rendering="crispEdges">']
    out.append("  <!-- AvocadoMTP app icon, concept B in pixel art (32×32 grid). "
               "Generated by tools/pixel_icon.py. -->")
    if rounded:
        out.append('  <clipPath id="r"><rect width="32" height="32" rx="7.2"/></clipPath><g clip-path="url(#r)">')
    # merge horizontal runs of the same color to keep the file small
    for y, row in enumerate(g):
        x = 0
        while x < N:
            c = row[x]
            run = 1
            while x + run < N and row[x + run] == c:
                run += 1
            out.append(f'  <rect x="{x}" y="{y}" width="{run}" height="1" fill="{PALETTE[c]}"/>')
            x += run
    if rounded:
        out.append("</g>")
    out.append("</svg>")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    dest = os.path.join(here, "..", "appicon")
    grid = build()
    with open(os.path.join(dest, "B-pixel.svg"), "w") as f:
        f.write(svg(grid, rounded=False))
    with open(os.path.join(dest, "B-pixel-preview.svg"), "w") as f:
        f.write(svg(grid, rounded=True))
    print("wrote appicon/B-pixel.svg and appicon/B-pixel-preview.svg")
